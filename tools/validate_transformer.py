"""Numerically validate a TensorRT TinySR transformer against its export-time golden.

Uses CUDA via PyTorch only for allocating buffers and invoking the TensorRT engine;
production TinySR-Jetson inference remains in C++.
"""

import argparse
from pathlib import Path


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--engine", type=Path, required=True,
                        help="Newly built tinysr_transformer_64_fp16.engine")
    parser.add_argument("--golden", type=Path, required=True,
                        help="Golden generated by the SAME exporter run as the ONNX")
    parser.add_argument("--max-relative-rmse", type=float, default=0.01,
                        help="Fail if relative RMSE exceeds this value (default: 0.01)")
    parser.add_argument("--min-close-fraction", type=float, default=0.99,
                        help="Fail if fewer than this fraction of values are close (default: 0.99)")
    args = parser.parse_args()

    import torch
    import tensorrt as trt
    from safetensors.torch import load_file

    if not torch.cuda.is_available():
        parser.error("CUDA-enabled PyTorch is required for this validation")
    if not args.engine.is_file() or not args.golden.is_file():
        parser.error("Both --engine and --golden must point to existing files")

    data = load_file(str(args.golden), device="cpu")
    required = {"latent_input", "prediction_merged"}
    if not required.issubset(data):
        raise ValueError(f"Golden is missing keys: {required - set(data)}")

    expected_shape = (1, 16, 64, 64)
    input_cpu = data["latent_input"]
    reference = data["prediction_merged"].float()
    if tuple(input_cpu.shape) != expected_shape or tuple(reference.shape) != expected_shape:
        raise ValueError("Unexpected golden tensor shape; expected (1, 16, 64, 64)")

    logger = trt.Logger(trt.Logger.WARNING)
    runtime = trt.Runtime(logger)
    engine = runtime.deserialize_cuda_engine(args.engine.read_bytes())
    if engine is None:
        raise RuntimeError("TensorRT could not deserialize the engine")
    context = engine.create_execution_context()
    if context is None:
        raise RuntimeError("TensorRT could not create an execution context")

    for name, mode in (("latent_input", trt.TensorIOMode.INPUT),
                       ("prediction", trt.TensorIOMode.OUTPUT)):
        if engine.get_tensor_mode(name) != mode:
            raise RuntimeError(f"Unexpected TensorRT tensor name or mode: {name}")
        if engine.get_tensor_dtype(name) != trt.DataType.HALF:
            raise RuntimeError(f"Expected FP16 TensorRT I/O for {name}")
        if tuple(context.get_tensor_shape(name)) != expected_shape:
            raise RuntimeError(f"Unexpected TensorRT shape for {name}")
    if engine.num_io_tensors != 2:
        raise RuntimeError(f"Expected 2 TensorRT I/O tensors, got {engine.num_io_tensors}")

    stream = torch.cuda.Stream()
    with torch.cuda.stream(stream):
        device_input = input_cpu.to(device="cuda", dtype=torch.float16).contiguous()
        device_output = torch.empty(expected_shape, device="cuda", dtype=torch.float16)
        if not context.set_tensor_address("latent_input", device_input.data_ptr()):
            raise RuntimeError("Failed to bind latent_input")
        if not context.set_tensor_address("prediction", device_output.data_ptr()):
            raise RuntimeError("Failed to bind prediction")
        if not context.execute_async_v3(stream.cuda_stream):
            raise RuntimeError("TensorRT inference failed")
    stream.synchronize()

    actual = device_output.float().cpu()
    if not bool(torch.isfinite(actual).all()):
        raise RuntimeError("TensorRT output contains NaN or Inf")

    diff = actual - reference
    abs_diff = diff.abs()
    rmse = diff.square().mean().sqrt().item()
    reference_rms = reference.square().mean().sqrt().item()
    relative_rmse = rmse / max(reference_rms, 1e-8)
    close_fraction = torch.isclose(actual, reference, atol=0.01, rtol=0.01).float().mean().item()

    print(f"Engine: {args.engine}")
    print(f"Golden: {args.golden}")
    print(f"Shape: {tuple(actual.shape)}")
    print(f"MAE: {abs_diff.mean().item():.9f}")
    print(f"RMSE: {rmse:.9f}")
    print(f"Relative RMSE: {relative_rmse:.9f} ({relative_rmse*100:.4f}%)")
    print(f"Max absolute error: {abs_diff.max().item():.9f}")
    print(f"P99 absolute error: {torch.quantile(abs_diff.flatten(), 0.99).item():.9f}")
    print(f"Within atol=rtol=0.01: {close_fraction*100:.4f}%")
    print("All finite: True")

    ok = relative_rmse <= args.max_relative_rmse and close_fraction >= args.min_close_fraction
    print("RESULT:", "PASS" if ok else "FAIL")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
